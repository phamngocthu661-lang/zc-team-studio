#!/usr/bin/env python3
"""QA-owned seal of reviewer diagnostics; does not author prose or infer quality.
Input review JSON authored after independent full manuscript read, NOT generated by tool.
Use one round 0 baseline audit, then at most one round 1 postrepair re-audit.
"""
import argparse,hashlib,json,sys
from pathlib import Path

def sha(b):return hashlib.sha256(b).hexdigest()
def canon(x):return json.dumps(x,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode('utf-8')
def die(s):raise ValueError(s)
ISSUES={'LOGIC','TIMELINE','MONEY','MOTIVATION','KNOWLEDGE','ACCESS','LEGAL','PHYSICAL','NAME','CONTINUITY','ORTHOGRAPHY','GRAMMAR','PUNCTUATION','ES_MX'}
def freeze(ns):
 from verify_full_script import report
 doc=report(ns.script)
 if not doc['pass']:die('Full manuscript is not verifiably within seven-Part length gate: '+str(doc['failures']))
 review=json.loads(ns.review.read_text('utf-8')); raw=ns.script.read_bytes()
 from narrative_consistency import check_review
 narrative_issues, narrative_warnings=check_review(raw.decode('utf-8','strict'), review)
 if narrative_issues:die('QA narrative preflight failed: '+'; '.join(narrative_issues))
 title=ns.title
 outline=ns.outline_file.read_bytes();osh=sha(outline);vid=sha((title+'\n'+osh).encode('utf-8'))[:16]
 round_=review.get('repair_round')
 if type(round_)!=int or round_ not in (0,1):die('repair_round must be exactly 0 or 1; no second repair')
 findings=review.get('findings')
 if not isinstance(findings,list):die('findings must be real reviewer list')
 if review.get('independent_full_read_confirmed') is not True:die('No independent read confirmation; cannot freeze or claim QA verdict')
 score=review.get('score')
 if type(score) not in (int,float) or not 0<=score<=100:die('Score must be independently entered 0..100')
 if review.get('hard_gate_pass') is not True:die('Hard gate fails; use a checkpoint/report, not frozen READY')
 ids=set(); strong=review.get('strong_span_ledger',[])
 if not isinstance(strong,list):die('strong_span_ledger must be list')
 for z in strong:
  if not isinstance(z,dict) or not isinstance(z.get('anchor'),str) or not z['anchor'] or z['anchor'].encode('utf-8') not in raw:
   die('Protected strong quote must occur exactly in original script')
 for p in findings:
  if not isinstance(p,dict):die('Finding must be object')
  if p.get('id') in ids or not isinstance(p.get('id'),str) or not p['id'].startswith('P'):die('Duplicate/bad finding ID')
  ids.add(p['id'])
  if p.get('classification') not in ISSUES:die('Finding type not in one-time logic/orthography repair scope: '+str(p.get('classification')))
  if p.get('part') not in ['Part '+str(i) for i in range(1,8)]:die('Finding Part invalid')
  if not isinstance(p.get('anchor'),str) or not p['anchor'] or p['anchor'].encode('utf-8') not in raw:die('Finding anchor must be exact source quote')
  if not p.get('problem') or not p.get('acceptance_tests'):die('Finding needs precise defect and acceptance test')
  if 'length_intent' not in p:p['length_intent']='KEEP'
 if round_==1:
  if not ns.repair_proof or not ns.baseline or not ns.contract or not ns.baseline_frozen:die('Postrepair QA requires real repair proof, original baseline, original frozen QA, and frozen contract')
  from verify_repair_provenance import verify as independent_verify
  verified=independent_verify(ns.baseline,ns.script,ns.contract,ns.repair_proof,ns.baseline_frozen)
  if not verified['pass']:die('Independent byte comparison FAILED')
  proof=json.loads(ns.repair_proof.read_text('utf-8'))
  if proof.get('schema')!='PADRE_MX_WRITER_REPAIR_PROOF_V1' or proof.get('revised_file_sha256')!=sha(raw) or proof.get('video_id')!=vid or proof.get('repair_round')!=1:
   die('Postrepair source/proof/video identity mismatch')
  # Review cannot reopen repair, even if finding remains.
 status='READY' if score>=98 and not findings else ('NOT_READY_REPAIR_ELIGIBLE' if round_==0 and findings else 'BLOCKED_FINAL_NO_MORE_REPAIRS')
 out={'schema':'PADRE_MX_QA_FROZEN_V1','title':title,'video_id':vid,'outline_sha256':osh,'repair_round':round_,
      'frozen_source':{'file_sha256':sha(raw),'body_sha256':doc['script_body_sha256'],'length_gate':'PASS','headings':list(range(1,8))},
      'frozen_baseline_score':score,'hard_gate_pass':True,'independent_full_read_confirmed':True,
      'publication_readiness':status,'frozen_patch_ledger':findings,
      'strong_span_ledger':strong,'reviewer_evidence':review.get('reviewer_evidence',[]),
      'narrative_preflight':{'pass':True,'warning_count':len(narrative_warnings),'warnings':narrative_warnings},
      'review_limits':'Quality and correctness reviewed by editor; software validates lineage, not subjective literary quality.'}
 if round_==1:out['repair_proof_sha256']=sha(ns.repair_proof.read_bytes())
 out['manifest_sha256']=sha(canon(out))
 if ns.out.exists():die('QA artifact exists; version outputs instead of overwriting frozen verdict')
 ns.out.parent.mkdir(parents=True,exist_ok=True)
 ns.out.write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 return {'pass':True,'qa_path':str(ns.out),'score':score,'repair_round':round_,'publication_readiness':status,'source_sha256':sha(raw),'findings':len(findings)}
if __name__=='__main__':
 ap=argparse.ArgumentParser()
 for arg in ('script','outline-file','review','out'):ap.add_argument('--'+arg,type=Path,required=True,dest=arg.replace('-','_'))
 ap.add_argument('--title',required=True);ap.add_argument('--repair-proof',type=Path);ap.add_argument('--baseline',type=Path);ap.add_argument('--contract',type=Path);ap.add_argument('--baseline-frozen',type=Path)
 ns=ap.parse_args()
 try:r=freeze(ns)
 except (ValueError,OSError,TypeError,KeyError,UnicodeError,json.JSONDecodeError) as e:r={'pass':False,'error':str(e)}
 print(json.dumps(r,ensure_ascii=False,indent=2));sys.exit(0 if r['pass'] else 2)
