test('batch UI chỉ chọn stock video trong folder, không hiện stock cùng tên', () => {
  const html = fs.readFileSync(path.join(__dirname, '../src/renderer/index.html'), 'utf8');
  const match = html.match(/<select id="backgroundMode">([\s\S]*?)<\/select>/);
  assert.ok(match, 'missing backgroundMode select');
  assert.doesNotMatch(match[1], /MATCHED_STOCK/);
  assert.match(match[1], /STOCK_VIDEO/);
});

