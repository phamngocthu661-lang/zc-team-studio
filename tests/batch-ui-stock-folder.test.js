function htmlForBatch() {
  const html = fs.readFileSync(path.join(__dirname, '../src/renderer/index.html'), 'utf8');
  return html.match(/<section id="page-batch"[\s\S]*?<\/section>\s*<section id="page-queue"/)?.[0] || '';
}

